"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { type ReactNode, useId, useState } from "react";

import type { PublicUrlWithPasswordDto } from "@/types/localify";

import {
  CheckIcon,
  DangerTriangleIcon,
  EditIcon,
  LockIcon,
  LockOpenIcon,
  SpinnerIcon,
} from "@/components/icons";
import { Button } from "@/components/ui/button";
import { DialogBody, DialogClose, DialogFooter } from "@/components/ui/dialog";
import { InputGroup, InputGroupAddon, InputGroupInput } from "@/components/ui/input-group";
import { Skeleton } from "@/components/ui/skeleton";
import { Switch } from "@/components/ui/switch";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { useDebouncedValue } from "@/hooks/use-debounced-value";
import { cloudMutations, cloudQueries } from "@/lib/queries";
import {
  isDnsLabel,
  maxEnvironmentLabel,
  publicDomainOf,
  type PublicUrlTarget,
  urlNamed,
} from "@/lib/util.cloud";
import { cn } from "@/lib/utils";
import { publicUrlSlugSchema } from "@/lib/validators/validator.cloud";

interface PublicUrlCreateFormProps {
  /** The domain the dialog opened for. */
  localDomain: string;
  target: PublicUrlTarget;
  /** Names the project a wildcard target belongs to. */
  projectName: string;
  onCreated: (result: PublicUrlWithPasswordDto) => void;
}

/**
 * One URL per project, as locally: the preview shows exactly where the domain will open, the
 * name comes from the local one and can be changed, and a password is generated by default.
 */
export const PublicUrlCreateForm = ({
  localDomain,
  target,
  projectName,
  onCreated,
}: PublicUrlCreateFormProps) => {
  const queryClient = useQueryClient();
  const suggestion = useQuery(cloudQueries.slugSuggestion(target.localDomain));
  const createPublicUrl = useMutation(cloudMutations.createPublicUrl(queryClient));
  /** The name being typed; null while the suggestion is used. */
  const [draft, setDraft] = useState<string | null>(null);
  const [passwordOn, setPasswordOn] = useState(true);
  const [submitError, setSubmitError] = useState<string | null>(null);
  const passwordSwitchId = useId();
  const status = useSlugStatus(draft);

  const suggested = suggestion.data?.slug ?? null;
  // Localify Cloud owns the public domain: every preview is built on the URL it suggested.
  const suggestedUrl = suggestion.data?.url ?? null;
  const editing = draft !== null;
  // The name in the preview: what was typed, even malformed, else the suggestion.
  const shownSlug = editing ? normalizeSlug(draft) : suggested;
  const chosenSlug = editing ? (status?.slug ?? null) : suggested;
  const canCreate =
    !createPublicUrl.isPending &&
    chosenSlug !== null &&
    (!editing || status?.state === "available");

  const handleCreate = async () => {
    if (chosenSlug === null) return;
    setSubmitError(null);
    const slug = chosenSlug;
    try {
      const result = await createPublicUrl.mutateAsync({
        localDomain: target.localDomain,
        wildcard: target.wildcard,
        slug,
        mode: passwordOn ? "password" : "public",
      });
      onCreated(result);
    } catch (error) {
      // Someone took the name since it was checked: let the person pick another.
      if (await isTaken(slug)) {
        setDraft(slug);
        void queryClient.invalidateQueries({
          queryKey: cloudQueries.slugSuggestion(target.localDomain).queryKey,
        });
        return;
      }
      setSubmitError(error instanceof Error ? error.message : String(error));
    }
  };

  const isTaken = async (slug: string) => {
    try {
      const check = await queryClient.fetchQuery({ ...cloudQueries.slugCheck(slug), staleTime: 0 });
      return !check.available;
    } catch {
      return false;
    }
  };

  const pencil = editing ? null : (
    <Tooltip>
      <TooltipTrigger
        render={
          <Button
            type="button"
            size="icon-xs"
            variant="ghost"
            aria-label="Change the name"
            disabled={suggested === null}
            onClick={() => setDraft(suggested ?? "")}
          >
            <EditIcon />
          </Button>
        }
      />
      <TooltipContent>Change the name</TooltipContent>
    </Tooltip>
  );

  return (
    // A grid item like the dialog's other parts: min-w-0 keeps a long URL from widening it.
    <form
      noValidate
      className="grid min-w-0 gap-6"
      onSubmit={(event) => {
        event.preventDefault();
        if (canCreate) void handleCreate();
      }}
    >
      <DialogBody className="min-w-0 space-y-5">
        <section
          aria-label="Public URL preview"
          className="min-w-0 space-y-2 rounded-xl border border-border/60 bg-background/70 p-3"
        >
          <PreviewUrl
            url={suggestedUrl}
            slug={shownSlug}
            label={target.label}
            loading={suggestion.isPending}
            dimmed={editing && status?.state === "invalid"}
            action={target.label === null ? pencil : null}
          />
          {target.label !== null ? (
            <div className="flex min-w-0 items-center gap-1.5 px-1 text-xs text-muted-foreground">
              <span className="shrink-0">Project URL</span>
              {suggestedUrl === null ? (
                <Skeleton className="h-3.5 w-40" />
              ) : (
                <span
                  className={cn(
                    "min-w-0 truncate font-mono",
                    editing && status?.state === "invalid"
                      ? "text-muted-foreground"
                      : "text-foreground",
                  )}
                >
                  {previewUrl(suggestedUrl, shownSlug, null)}
                </span>
              )}
              {pencil}
            </div>
          ) : null}
          {suggestion.error ? (
            <p
              role="alert"
              className="flex flex-wrap items-center gap-x-2 px-1 text-xs text-destructive"
            >
              Could not suggest a name: {suggestion.error.message}
              <Button
                type="button"
                size="xs"
                variant="ghost"
                loading={suggestion.isFetching}
                onClick={() => void suggestion.refetch()}
              >
                Try again
              </Button>
            </p>
          ) : null}
          {editing && suggestedUrl !== null ? (
            <SlugEditor
              domain={publicDomainOf(suggestedUrl)}
              value={draft}
              status={status}
              suggested={suggested}
              onChange={setDraft}
              onUseSuggested={() => setDraft(null)}
            />
          ) : null}
        </section>

        {target.wildcard && suggestedUrl !== null ? (
          <p className="text-xs leading-normal text-muted-foreground">
            Every service and worktree of {projectName} opens at{" "}
            <span className="font-mono whitespace-nowrap text-foreground">
              {shownSlug || "<name>"}--&lt;service&gt;.{publicDomainOf(suggestedUrl)}
            </span>
            .
          </p>
        ) : null}

        {target.label !== null && chosenSlug ? (
          <LabelFit localDomain={localDomain} label={target.label} slug={chosenSlug} />
        ) : null}

        <div className="space-y-2">
          <div className="flex items-start gap-3">
            <span
              aria-hidden
              className="flex size-8 shrink-0 items-center justify-center rounded-lg bg-muted text-foreground/80 ring-1 ring-border/60 [&>svg]:size-4"
            >
              {passwordOn ? <LockIcon /> : <LockOpenIcon />}
            </span>
            <label htmlFor={passwordSwitchId} className="min-w-0 flex-1 cursor-pointer">
              <span className="block text-sm font-medium text-foreground">Password</span>
              <span className="block text-xs leading-normal text-muted-foreground">
                {passwordOn
                  ? "Localify generates one. Each browser asks for it once, then stays signed in for 7 days. You can change it later."
                  : "No password: the URL opens for anyone."}
              </span>
            </label>
            <Switch
              id={passwordSwitchId}
              checked={passwordOn}
              onCheckedChange={(checked) => setPasswordOn(checked)}
            />
          </div>
          {passwordOn ? null : (
            <p
              role="alert"
              className="flex items-start gap-1.5 text-xs leading-normal text-amber-700 dark:text-amber-300"
            >
              <DangerTriangleIcon className="mt-0.5 size-3.5 shrink-0" />
              <span>
                Anyone with the link can open{" "}
                {target.wildcard ? (
                  `every service and worktree of ${projectName}`
                ) : (
                  <span className="font-mono">{localDomain}</span>
                )}
                , with no password.
              </span>
            </p>
          )}
        </div>

        {submitError ? (
          <p role="alert" className="text-xs text-destructive">
            {submitError}
          </p>
        ) : null}
      </DialogBody>

      <DialogFooter>
        <DialogClose render={<Button variant="outline" />}>Cancel</DialogClose>
        <Button type="submit" disabled={!canCreate} loading={createPublicUrl.isPending}>
          {createPublicUrl.isPending ? "Creating…" : "Create public URL"}
        </Button>
      </DialogFooter>
    </form>
  );
};

/** `https://<slug>.<public domain>`, or `https://<slug>--<label>.<public domain>`, as typed. */
function previewUrl(url: string, slug: string | null, label: string | null): string {
  const name = slug || "<name>";
  return urlNamed(url, label === null ? name : `${name}--${label}`);
}

function normalizeSlug(value: string): string {
  return value.trim().toLowerCase();
}

interface PreviewUrlProps {
  /** The suggested URL, whose domain the preview keeps; null until it loads. */
  url: string | null;
  slug: string | null;
  label: string | null;
  loading: boolean;
  dimmed: boolean;
  action: ReactNode;
}

const PreviewUrl = ({ url, slug, label, loading, dimmed, action }: PreviewUrlProps) => (
  <div className="flex min-h-8 min-w-0 items-center gap-1">
    {loading || url === null ? (
      <Skeleton className="mx-1 h-5 w-64 max-w-full" />
    ) : (
      <span
        className={cn(
          "min-w-0 flex-1 truncate px-1 font-mono text-sm",
          dimmed ? "text-muted-foreground" : "text-foreground",
        )}
      >
        {previewUrl(url, slug, label)}
      </span>
    )}
    {action}
  </div>
);

type SlugStatus =
  | { state: "invalid"; message: string; slug: null }
  | { state: "checking"; slug: string }
  | { state: "available"; slug: string }
  | { state: "taken"; slug: string }
  | { state: "error"; message: string; slug: string };

/** The format first, as `PublicSlug` checks it, then whether the name is free. */
function useSlugStatus(draft: string | null): SlugStatus | null {
  const slug = normalizeSlug(draft ?? "");
  const format = publicUrlSlugSchema.safeParse(slug);
  const debounced = useDebouncedValue(slug, 300);
  const check = useQuery({
    ...cloudQueries.slugCheck(debounced),
    enabled: draft !== null && format.success && debounced === slug,
  });

  if (draft === null) return null;
  if (!format.success) {
    return {
      state: "invalid",
      message: format.error.issues[0]?.message ?? "Check the name.",
      slug: null,
    };
  }
  if (debounced !== slug || check.isPending) return { state: "checking", slug };
  if (check.error) return { state: "error", message: check.error.message, slug };
  return { state: check.data.available ? "available" : "taken", slug };
}

interface SlugEditorProps {
  /** The public domain the name sits under. */
  domain: string;
  value: string;
  status: SlugStatus | null;
  suggested: string | null;
  onChange: (value: string) => void;
  onUseSuggested: () => void;
}

const SlugEditor = ({
  domain,
  value,
  status,
  suggested,
  onChange,
  onUseSuggested,
}: SlugEditorProps) => {
  const inputId = useId();
  const statusId = useId();
  const invalid = status?.state === "invalid" || status?.state === "taken";

  return (
    <div className="space-y-1.5 border-t border-border/40 pt-3">
      <label htmlFor={inputId} className="block px-1 text-xs font-medium text-foreground">
        Name
      </label>
      <div className="flex min-w-0 items-center gap-2">
        <InputGroup className="min-w-0 flex-1">
          <InputGroupInput
            id={inputId}
            value={value}
            autoFocus
            spellCheck={false}
            maxLength={40}
            aria-invalid={invalid || undefined}
            aria-describedby={statusId}
            className="font-mono"
            onChange={(event) => onChange(event.target.value.toLowerCase())}
          />
          <InputGroupAddon align="inline-end" className="font-mono font-normal">
            .{domain}
          </InputGroupAddon>
        </InputGroup>
        <Button type="button" size="sm" variant="ghost" onClick={onUseSuggested}>
          {suggested ? `Use ${suggested}` : "Cancel"}
        </Button>
      </div>
      <SlugStatusLine id={statusId} domain={domain} status={status} />
    </div>
  );
};

interface SlugStatusLineProps {
  id: string;
  domain: string;
  status: SlugStatus | null;
}

const SlugStatusLine = ({ id, domain, status }: SlugStatusLineProps) => {
  const line = (() => {
    switch (status?.state) {
      case undefined:
        return null;
      case "checking":
        return (
          <span className="flex items-center gap-1.5 text-muted-foreground">
            <SpinnerIcon className="size-3.5 animate-spin" />
            Checking…
          </span>
        );
      case "available":
        return (
          <span className="flex items-center gap-1.5 text-emerald-700 dark:text-emerald-400">
            <CheckIcon className="size-3.5" />
            Available
          </span>
        );
      case "taken":
        return (
          <span className="text-destructive">
            {status.slug}.{domain} is taken. Try another name.
          </span>
        );
      case "invalid":
      case "error":
        return <span className="text-destructive">{status.message}</span>;
    }
  })();

  return (
    <p id={id} aria-live="polite" className="min-h-4 px-1 text-xs">
      {line}
    </p>
  );
};

interface LabelFitProps {
  localDomain: string;
  label: string;
  slug: string;
}

/** Says when the project URL cannot reach the opened domain, rather than hiding it. */
const LabelFit = ({ localDomain, label, slug }: LabelFitProps) => {
  const max = maxEnvironmentLabel(slug);
  if (isDnsLabel(label) && label.length <= max) return null;
  return (
    <p className="flex items-start gap-1.5 text-xs leading-normal text-amber-700 dark:text-amber-300">
      <DangerTriangleIcon className="mt-0.5 size-3.5 shrink-0" />
      <span>
        {isDnsLabel(label) ? (
          <>
            The project URL cannot reach <span className="font-mono">{localDomain}</span>:{" "}
            <span className="font-mono">{label}</span> has {label.length} characters, and a name of{" "}
            {slug.length} leaves room for {max}. Choose a shorter name to reach it.
          </>
        ) : (
          <>
            The project URL cannot reach <span className="font-mono">{localDomain}</span>, which
            sits more than one level under the project.
          </>
        )}
      </span>
    </p>
  );
};
