const Anchor = ({
  href,
  className,
  children,
  ...props
}: {
  href: string;
  className?: string;
  children: ReactNode;
} & Omit<AnchorHTMLAttributes<HTMLAnchorElement>, "className" | "href">) => {
  if (href.startsWith("/")) {
    return (
      <Link className={className} href={href} {...props}>
        {children}
      </Link>
    );
  }
  return (
    <a className={className} href={href} {...props}>
      {children}
    </a>
  );
};

