export function generatePassword(): string {
  const random = randomBytes(8);
  const words: string[] = [];
  for (let i = 0; i < 4; i++) {
    const index = ((random[i * 2]! << 8) | random[i * 2 + 1]!) % WORDS.length;
    words.push(WORDS[index]!);
  }
  return words.join("-");
}
